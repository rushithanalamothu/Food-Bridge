import { compile } from 'json-schema-to-typescript';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const input = new URL('../contracts/domain.schema.json', import.meta.url);
const output = new URL('../apps/web/src/api/generated/domain.ts', import.meta.url);
const schema = JSON.parse(await readFile(input, 'utf8'));
const content = await compile(schema, 'FoodBridgeContracts', {
  bannerComment: '/* Generated by make contracts. Edit Python domain/contracts.py instead. */',
  style: { singleQuote: true, trailingComma: 'all', printWidth: 100 },
  additionalProperties: false,
});
if (process.argv.includes('--check')) {
  if ((await readFile(output, 'utf8')) !== content) {
    throw new Error(`Stale generated types: ${fileURLToPath(output)}. Run make contracts.`);
  }
} else {
  await writeFile(output, content);
}
